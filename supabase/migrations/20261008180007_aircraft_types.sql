-- Słownik typów ICAO dla wybieraka na /settings. Pełna lista nie może trafić
-- do zasięgu modułu Workera (limit czasu startu), więc żyje w bazie i jest
-- odpytywana. Dane wchodzą migracją, bo seed.sql działa tylko przy lokalnym
-- db reset, a produkcja musi dostać słownik razem ze schematem.
create table public.aircraft_types (
  code     public.icao_type primary key,
  name     text not null check (name <> ''),
  -- Wyróżnione typy pokazywane jako przełączniki; zmiana listy to nowa migracja.
  featured boolean not null default false
);

-- Słownik jest tylko do odczytu z aplikacji: brak insert/update/delete na
-- poziomie uprawnień znaczy, że nawet błędnie dodana polityka ich nie
-- odblokuje. Domyślne uprawnienia Supabase dają authenticated wszystkie prawa
-- do nowych tabel, a grant ich nie odbiera — stąd revoke.
revoke all on public.aircraft_types from anon;
revoke all on public.aircraft_types from authenticated;
grant select on public.aircraft_types to authenticated;

alter table public.aircraft_types enable row level security;

-- Słownik jest wspólny dla wszystkich zalogowanych; anonim go nie czyta.
create policy "aircraft types readable"
  on public.aircraft_types for select
  to authenticated
  using (true);

